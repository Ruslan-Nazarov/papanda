def get_translator(locale: str):
    locale = (locale or "ru").lower()
    if locale not in TRANSLATIONS:
        locale = "ru"

    def _(key: str) -> str:
        return TRANSLATIONS[locale].get(key) or TRANSLATIONS["ru"].get(key, key)

    return _
